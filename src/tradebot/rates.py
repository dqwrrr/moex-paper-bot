"""Ключевая ставка ЦБ РФ — доходность «кэша» (фонд денежного рынка ≈ ставка − расходы фонда).

Таблица неполная (только даты изменений, влияющих на период данных) и используется
как приближение. Обновлять вручную при изменении ставки.
"""
from __future__ import annotations

import pandas as pd

# До 13.09.2013 ключевой ставки не было. Для 2003–2013 взяты ГРУБЫЕ оценки ставок
# денежного рынка (MIACR/депозиты), округлённые — только для проверки стратегий на длинной истории.
KEY_RATE_CHANGES: list[tuple[str, float]] = [
    ("2003-01-01", 5.0), ("2008-06-01", 7.0), ("2008-10-01", 10.0), ("2009-06-01", 7.0),
    ("2009-11-01", 5.0), ("2010-03-01", 4.0), ("2011-06-01", 5.0), ("2012-01-01", 6.0),
    ("2013-09-13", 5.50), ("2014-03-03", 7.00), ("2014-04-28", 7.50), ("2014-07-28", 8.00),
    ("2014-11-05", 9.50), ("2014-12-12", 10.50), ("2014-12-16", 17.00), ("2015-02-02", 15.00),
    ("2015-03-16", 14.00), ("2015-05-05", 12.50), ("2015-06-16", 11.50), ("2015-08-03", 11.00),
    ("2016-06-14", 10.50), ("2016-09-19", 10.00), ("2017-03-27", 9.75), ("2017-05-02", 9.25),
    ("2017-06-19", 9.00), ("2017-09-18", 8.50), ("2017-10-30", 8.25), ("2017-12-18", 7.75),
    ("2018-02-12", 7.50), ("2018-03-26", 7.25), ("2018-09-17", 7.50), ("2018-12-17", 7.75),
    ("2019-06-17", 7.50), ("2019-07-29", 7.25), ("2019-09-09", 7.00), ("2019-10-28", 6.50),
    ("2019-12-16", 6.25), ("2020-02-10", 6.00), ("2020-04-27", 5.50), ("2020-06-22", 4.50),
    ("2020-07-27", 4.25), ("2021-03-22", 4.50), ("2021-04-26", 5.00), ("2021-06-15", 5.50),
]

MONEY_MARKET_FEE = 1.2  # % годовых — расходы фонда денежного рынка (TMON@ ≈ 1,2%)


def cash_daily_returns(dates: pd.DatetimeIndex) -> pd.Series:
    """Дневная доходность кэша на каждую торговую дату (по календарным дням)."""
    ch = pd.Series({pd.Timestamp(d): r for d, r in KEY_RATE_CHANGES}).sort_index()
    rate = ch.reindex(ch.index.union(dates)).ffill().reindex(dates).fillna(ch.iloc[0])
    annual = (rate - MONEY_MARKET_FEE).clip(lower=0) / 100
    days = pd.Series(dates, index=dates).diff().dt.days.fillna(1)
    return (1 + annual) ** (days / 365) - 1
